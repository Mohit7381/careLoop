import { CodeGap, Finding, Remedy, RunState } from './run-state';

/**
 * The backend now returns the generated PRD as markdown (`prd_markdown` on
 * RunDetailResponse, surfaced as `RunState.prd_draft`), so on a live run the
 * drawer renders that directly — it is the real artifact the PRD Generator
 * wrote, not a client-side reconstruction.
 *
 * buildPrdView() is the FIXTURE-MODE fallback for when `prd_draft` is null:
 * it assembles an equivalent structured view from findings + code_gaps, both
 * of which are real. Prefer the markdown whenever it is present.
 */
export interface PrdView {
  banner: string;
  title: string;
  subtitle: string;
  overview: string;
  goals: [string, string][];
  requirements: [string, string][];
  openQuestions: [string, string][];
  channel: string;
}

/**
 * `rank` selects which finding this PRD is drafted for — defaults to the #1
 * ranked finding (the original, single-PRD behaviour). Passing another rank
 * (multi-PRD mode) re-titles from that finding's hypothesis and scopes the
 * functional-requirements list to only that finding's code gap(s), instead
 * of the pre-multi-PRD bug where every reconstructed PRD listed every gap's
 * remedies regardless of which finding it was drafted for.
 */
export function buildPrdView(run: RunState, rank = 1): PrdView {
  const sorted = [...run.findings].sort((a, b) => a.rank - b.rank);
  const top = sorted.find((f) => f.rank === rank) ?? sorted[0];
  const topGap = run.code_gaps.find((g) => g.finding_rank === top?.rank && g.mechanism_found)
    ?? run.code_gaps.find((g) => g.mechanism_found);

  return {
    banner: `DRAFT — generated by run #${run.run_id}, needs human review`,
    title: top && top.rank !== 1 ? `Fix: ${top.hypothesis.split('.')[0].slice(0, 80)}` : 'Pharmacy Checkout Rescue',
    subtitle: buildSubtitle(run, topGap),
    overview: buildOverview(top, topGap),
    goals: [
      ['Recover rx-gated abandons', 'recover 5% ≈ 3,400 delivered orders/week in the 79%-of-GMV segment'],
      ['Separate real abandons from artifacts', 'exclude address-change re-creates from the abandon count'],
      ['No increase in support contacts', 'payment/refund ticket volume flat or down'],
    ],
    requirements: buildRequirements(run, top?.rank),
    openQuestions: [
      ['What is timeToAbandonOrderInMinutes set to in prod?', 'timor/oms — config-driven, not in source'],
      [
        'Can sendCommunication be called from abandonOrderV2 directly, or does it need adapting for the timer-driven path?',
        'timor/oms — Code Scout verified it exists in the same file but not wired into this path',
      ],
      ['Can a resume link re-attach an existing eRx, or does it force a new consult?', 'bintan/consultation'],
      ['Are address-change re-creates linkable to the original cart?', 'timor/oms'],
    ],
    channel: '#funnel-hackathon',
  };
}

function buildSubtitle(run: RunState, gap: CodeGap | undefined): string {
  const ranks = run.findings.map((f) => `#${f.rank}`).join(', ');
  const remedies = run.code_gaps.reduce((n, g) => n + (g.remedies?.length ?? 0), 0);
  const gapPart = gap ? `${gap.repo} ${gap.file}:${gap.line}` : 'no mechanism pinned';
  return `Product Requirements Document · cites finding ${ranks} · ${gapPart} · ${remedies} remedy verdict(s)`;
}

function buildOverview(top: Finding | undefined, gap: CodeGap | undefined): string {
  if (!top) return 'No findings on this run.';
  if (!gap) return `${top.hypothesis}. Code Scout did not pin a mechanism for this finding.`;
  return `${top.hypothesis}. ${gap.gap_statement}`;
}

/** FR rows come from the Remedy Loop's own proposals, so the PRD mirrors what
 *  Code Scout actually searched for rather than a hand-written list.
 *
 *  Each row states the strength of its own evidence — an unverified remedy is
 *  a candidate to check, not a confirmed gap to build (PR #5, B3), and a
 *  not-found one says how many searches back that claim (B2). */
function buildRequirements(run: RunState, rank?: number): [string, string][] {
  const rows: [string, string][] = [];
  let n = 1;
  const order = (s: Remedy['status']) => (s === 'absent' ? 0 : s === 'partial' ? 1 : s === 'exists' ? 3 : 2);
  const gapsInScope = run.code_gaps.filter(
    (g) => g.mechanism_found && (rank == null || g.finding_rank === rank)
  );

  for (const gap of gapsInScope) {
    for (const r of [...(gap.remedies ?? [])].sort((a, b) => order(a.status) - order(b.status))) {
      const searches = r.searched_terms?.length ?? 0;
      const prefix =
        r.status === 'absent'
          ? `Not found in ${gap.repo} across ${searches} search${searches === 1 ? '' : 'es'}. `
          : r.status === 'partial'
            ? 'Partial match — related code exists, confirm before building. '
            : r.status === 'exists'
              ? 'Already present — verify before building. '
              : 'Not verified by the loop — check this one first. ';
      rows.push([`FR-${n++}`, `${prefix}${r.proposal}`]);
    }
  }
  if (!rows.length) rows.push([`FR-${n++}`, 'No verified remedies on this run — Code Scout pinned no mechanism.']);
  rows.push([`FR-${n++}`, 'Register the predicted recovery range before rollout; report realised vs predicted in the following run.']);
  return rows;
}

/**
 * Minimal markdown -> HTML for rendering the PRD Generator's real markdown
 * artifact (prd_generator.py's `_render_prd_llm_stub`, via templates/
 * prd_template.md) in the drawer instead of only ever reconstructing a
 * structured view from findings/code_gaps. Escapes first so this is safe to
 * bind with [innerHTML] even though the source is server-generated text
 * that itself interpolates finding hypotheses and VoC quotes. Only covers
 * what that template actually emits — headings, bold, inline code,
 * blockquotes, bullet lists, and paragraphs — not general-purpose markdown.
 */
export function renderPrdMarkdown(md: string): string {
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  let html = esc(md);

  html = html
    .replace(/^#### (.*)$/gm, '<h5>$1</h5>')
    .replace(/^### (.*)$/gm, '<h4>$1</h4>')
    .replace(/^## (.*)$/gm, '<h3>$1</h3>')
    .replace(/^# (.*)$/gm, '<h2>$1</h2>')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/^&gt; (.*)$/gm, '<blockquote>$1</blockquote>');

  html = html.replace(/^- (.*)$/gm, '<li>$1</li>');
  html = html.replace(/(?:<li>.*<\/li>\n?)+/g, (block) => `<ul>${block}</ul>`);

  return html
    .split(/\n{2,}/)
    .map((block) => {
      const trimmed = block.trim();
      if (!trimmed) return '';
      if (/^<(h\d|ul|blockquote)/.test(trimmed)) return trimmed;
      return `<p>${trimmed.replace(/\n/g, '<br>')}</p>`;
    })
    .join('\n');
}
