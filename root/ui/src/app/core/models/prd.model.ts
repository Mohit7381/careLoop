import { Finding, RunState, Suggestion } from './run-state';

/**
 * contracts.py's `RunState.prd_draft` is `Optional[str]` (markdown) — the
 * real PRD Generator (Mohit's node) has not shipped yet, so there is
 * nothing to render from prd_draft on the fixture or on a Day-1 live run.
 *
 * This builds an equivalent structured view FROM findings + suggestions
 * (Rev 3), which are real and already implemented (Nakul's Analyst /
 * Harshit's Code Scout). When prd_draft starts arriving as markdown,
 * PrdDrawerComponent should prefer rendering that directly and this builder
 * becomes the fixture-mode fallback — see PrdDrawerComponent.hasMarkdown().
 */
export interface PrdView {
  banner: string;
  title: string;
  subtitle: string;
  overview: string;
  goals: [string, string][];
  requirements: [string, string][];
  openQuestions: [string, string][];
  channel: string;
}

export function buildPrdView(run: RunState): PrdView {
  const top = [...run.findings].sort((a, b) => a.rank - b.rank)[0];
  const topSuggestions = run.suggestions.filter((s) => s.finding_rank === top?.rank);

  return {
    banner: `DRAFT — generated by run #${run.run_id}, needs human review`,
    title: 'Pharmacy Checkout Rescue',
    subtitle: buildSubtitle(run, topSuggestions),
    overview: buildOverview(top, topSuggestions),
    goals: [
      ['Recover rx-gated abandons', 'recover 5% ≈ 3,400 delivered orders/week in the 79%-of-GMV segment'],
      ['Separate real abandons from artifacts', 'exclude address-change re-creates from the abandon count'],
      ['No increase in support contacts', 'payment/refund ticket volume flat or down'],
    ],
    requirements: buildRequirements(run),
    openQuestions: [
      ['What is timeToAbandonOrderInMinutes set to in prod?', 'timor/oms — config-driven, not in source'],
      [
        'Can sendCommunication be called from abandonOrderV2 directly, or does it need adapting for the timer-driven path?',
        'timor/oms — the capability exists in BaseCancellationTypeAdapterService.java:216, 82 lines from ' +
          'abandonOrderV2 (partial, not exists — Code Scout flagged this as not proven wired in)',
      ],
      ['Can a resume link re-attach an existing eRx, or does it force a new consult?', 'bintan/consultation'],
      ['Are address-change re-creates linkable to the original cart?', 'timor/oms'],
    ],
    channel: '#funnel-hackathon',
  };
}

function buildSubtitle(run: RunState, topSuggestions: Suggestion[]): string {
  const ranks = run.findings.map((f) => `#${f.rank}`).join(', ');
  const techCount = topSuggestions.filter((s) => s.suggestion_type === 'tech').length;
  const otherCount = topSuggestions.length - techCount;
  const suggPart = topSuggestions.length
    ? `${techCount} tech + ${otherCount} business/process suggestion(s)`
    : 'no suggestions yet';
  return `Product Requirements Document · cites finding ${ranks} · ${suggPart}`;
}

function buildOverview(top: Finding | undefined, topSuggestions: Suggestion[]): string {
  if (!top) return 'No findings on this run.';
  if (!topSuggestions.length) {
    return `${top.hypothesis}. Code Scout has not explored a matching repo for this finding yet.`;
  }
  // Prefer a tech suggestion's rationale (it's code-grounded); fall back to
  // whatever suggestion ranks first.
  const lead = topSuggestions.find((s) => s.suggestion_type === 'tech') ?? topSuggestions[0];
  return `${top.hypothesis}. ${lead.rationale}`;
}

function buildRequirements(run: RunState): [string, string][] {
  // Turn each finding's suggestions into FR rows, tech first per finding,
  // so the PRD mirrors what Code Scout actually proposed rather than a
  // hand-written list disconnected from the run.
  const rows: [string, string][] = [];
  let n = 1;
  for (const finding of [...run.findings].sort((a, b) => a.rank - b.rank)) {
    const suggestions = [...run.suggestions.filter((s) => s.finding_rank === finding.rank)].sort((a, b) =>
      a.suggestion_type === b.suggestion_type ? 0 : a.suggestion_type === 'tech' ? -1 : 1
    );
    for (const s of suggestions) {
      rows.push([`FR-${n++}`, `${s.title}. ${s.description}`]);
    }
  }
  rows.push([`FR-${n++}`, 'Register the predicted recovery range before rollout; report realised vs predicted in the following run.']);
  return rows;
}
